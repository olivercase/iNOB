#!/usr/bin/env python3
"""Topographies of the HEP and the CFA across head orientations.

The claim the 2x2 rests on, drawn: the array is rigidly fixed to the skull and
brain, so the **HEP topography is identical at every head orientation**, while the
heart stays in the torso frame so the **CFA topography changes**. One figure per
source, nine panels each, on the SAME colour scale within a figure.

Everything is plotted in the HEAD frame -- the still-head sensor layout -- for
every panel. That is not a convenience: channel k is the same physical sensor at
every orientation, so holding the layout fixed is what makes "the same
topography" a visible statement rather than an arithmetic one.

Radial channels only (the first 85 of 255). The two tangential axes carry real
signal and are used by every estimator; they are simply not what a scalp
topography is for.

    python scripts/plot_cfa_topo.py
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from scipy.interpolate import Rbf

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from inob.cfa.array import CFAArray
from inob.cfa.design import DESIGN
from inob.cfa.posture import rotation_matrix


def flatten(pos: np.ndarray) -> np.ndarray:
    """Azimuthal-equidistant projection of sensor positions onto a disc.

    Distance from the vertex is arc length along the fitted sphere, so a sensor
    at the equator lands at radius pi/2 and the map stays area-fair enough for a
    scalp layout. This is the same construction FieldTrip's layouts use.
    """
    c = pos.mean(0)
    v = pos - c
    r = np.linalg.norm(v, axis=1)
    u = v / r[:, None]
    theta = np.arccos(np.clip(u[:, 2], -1, 1))          # from +z (vertex)
    phi = np.arctan2(u[:, 1], u[:, 0])
    return np.stack([theta * np.cos(phi), theta * np.sin(phi)], 1)


def head_inset(ax, ypr, *, heart_bearing_deg: float | None = None):
    """Top-down schematic of where the head is pointing, in the ROOM.

    The topographies are drawn in the head-fixed layout, which is what makes the
    HEP look identical -- but it also hides the very thing that is moving. This
    inset puts the room back: the silhouette turns with the head, the fixed
    marker is the heart, and the wedge is the heart's bearing in the head frame,
    which is the direction the CFA gradient points.
    """
    yaw, pitch, roll = np.asarray(ypr, float).ravel()
    ax.set_xlim(-1.5, 1.5); ax.set_ylim(-1.5, 1.5)
    ax.set_aspect("equal"); ax.axis("off")
    th = np.linspace(0, 2 * np.pi, 200)
    ax.plot(np.cos(th), np.sin(th), color="0.55", lw=0.9)     # the room / trunk
    a = np.deg2rad(yaw)
    # head silhouette: a disc with a nose, rotated by yaw
    hx, hy = 0.62 * np.cos(th), 0.62 * np.sin(th)
    ax.fill(hx, hy, color="0.90", zorder=2)
    ax.plot(hx, hy, color="0.35", lw=1.0, zorder=3)
    nose = np.array([[0.0, 0.86], [-0.16, 0.58], [0.16, 0.58]])
    rot = np.array([[np.cos(a), -np.sin(a)], [np.sin(a), np.cos(a)]])
    nz = nose @ rot.T
    ax.fill(nz[:, 0], nz[:, 1], color="0.35", zorder=4)
    ax.scatter([0], [-1.0], s=52, marker="v", color="#c8323c", zorder=5,
               clip_on=False)                                  # heart: fixed below
    ax.plot([0, 0], [-0.62, -0.94], color="#c8323c", lw=1.0, ls=":", zorder=1)


def topo(ax, xy: np.ndarray, val: np.ndarray, vlim: float, *, n: int = 160,
         heart_xy: np.ndarray | None = None, yaw_deg: float = 0.0):
    """Draw one map. ``yaw_deg`` physically turns the head on the page.

    With ``yaw_deg`` the map is drawn in the ROOM's frame rather than the head's:
    the layout, the head outline and the nose all rotate together, while the
    heart marker stays where it actually is -- below and in front, never moving.
    Read that way the figure states the physics directly. The CFA is generated by
    a source fixed in the room, so its pattern should sit still on the page while
    the head spins under it; the HEP is generated inside the head, so its pattern
    should turn with the nose. Neither statement is visible in a head-fixed
    layout, where both maps are pinned to the same sensor positions.
    """
    a = np.deg2rad(yaw_deg)
    rot2 = np.array([[np.cos(a), -np.sin(a)], [np.sin(a), np.cos(a)]])
    xy = xy @ rot2.T
    r_max = np.linalg.norm(xy, axis=1).max() * 1.06
    g = np.linspace(-r_max, r_max, n)
    gx, gy = np.meshgrid(g, g)
    z = Rbf(xy[:, 0], xy[:, 1], val, function="multiquadric",
            smooth=0.02)(gx, gy)
    z[gx ** 2 + gy ** 2 > r_max ** 2] = np.nan
    im = ax.contourf(gx, gy, z, levels=np.linspace(-vlim, vlim, 25),
                     cmap="RdBu_r", extend="both")
    ax.contour(gx, gy, z, levels=np.linspace(-vlim, vlim, 13), colors="k",
               linewidths=0.25, alpha=0.35)
    ax.add_artist(plt.Circle((0, 0), r_max, fill=False, lw=1.4, color="0.25"))
    nose = rot2 @ np.array([0.0, r_max])                       # nose turns too
    ax.plot([nose[0]], [nose[1]], marker=(3, 0, yaw_deg), ms=11, color="0.25",
            clip_on=False, zorder=8)
    ax.scatter(xy[:, 0], xy[:, 1], s=2.2, c="k", alpha=0.55, zorder=5)
    if heart_xy is not None:
        u = heart_xy / (np.linalg.norm(heart_xy) or 1.0)
        ax.scatter([u[0] * r_max * 1.30], [u[1] * r_max * 1.30], s=95, marker="v",
                   color="#c8323c", zorder=30, clip_on=False)

    ax.set_xlim(-1.45 * r_max, 1.45 * r_max)
    ax.set_ylim(-1.45 * r_max, 1.45 * r_max)
    ax.set_aspect("equal"); ax.axis("off")
    return im


def main(argv=None) -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--dir", type=Path,
                   default=Path(__file__).resolve().parents[1] / "outputs/cfa_forward")
    p.add_argument("--source-nam", type=float, default=10.0,
                   help="insula source strength, nA.m")
    p.add_argument("--dpi", type=int, default=165)
    a = p.parse_args(argv)

    files = sorted(a.dir.glob("orient_*.npz"))
    if not files:
        raise SystemExit(f"no orient_*.npz in {a.dir} -- run build_cfa_forward.py")
    s = np.load(a.dir / "sources.npz")
    myo_ori, q = s["myo_ori"], s["q"]
    erp = int(s["erp_index"])
    rpk = int(np.linalg.norm(q, axis=0).argmax())

    array = CFAArray.from_reference(
        Path(__file__).resolve().parents[1] / "outputs/_cfa_ref.npz")
    n_site = array.n_site
    xy = flatten(array.site_pos_mm)          # still-head layout, used for every panel

    # myocardial site amplitudes from the measured moment
    w = s["myo_area_mm2"] / s["myo_area_mm2"].mean()
    nw = (myo_ori * w[:, None]).T
    amps = w[:, None] * (nw.T @ np.linalg.solve(nw @ nw.T, q))

    # Where the heart sits IN THE HEAD FRAME. The heart never moves in the room;
    # the head turns, so in the head's own coordinates the heart swings around it.
    # That bearing is what sets the direction of the CFA gradient across the array,
    # which is why it is drawn on the map.
    import json
    post = json.loads((Path(__file__).resolve().parents[1]
                       / "outputs/cfa_thorax/posture.json").read_text())
    pivot = np.asarray(post["neck"]["pivot_mm"], float)
    heart_c = np.asarray(s["heart_centroid_mm"]) if "heart_centroid_mm" in s.files \
        else np.asarray([-21.2, 3.9, -320.9])
    c_layout = array.site_pos_mm.mean(0)

    hep, cfa_r, cfa_t, names, yprs, heart_xy = [], [], [], [], [], []
    for f in files:
        d = np.load(f)
        ypr = d["ypr_deg"]
        yprs.append(ypr)
        # In the ROOM's frame the heart bearing is the same on every panel -- it
        # is the head that moves. Drawn once, fixed, so the eye has an anchor.
        v = heart_c - pivot
        heart_xy.append(np.array([v[0], v[1]]) /
                        (np.linalg.norm(v[:2]) or 1.0))
        names.append("still" if not np.any(ypr) else
                     "{:+.0f}/{:+.0f}/{:+.0f}".format(*ypr))
        ori = d["chanori"]
        # HEP: 3-dof insula source, unit moment along [1,1,1]/sqrt(3) IN THE HEAD
        # FRAME, scaled to nA.m. The moment must rotate with the brain -- it is an
        # anatomical property of the generator, not a direction in the room. Held
        # fixed in world coordinates instead, the dipole points somewhere different
        # in the head at every orientation and the topography correlation collapses
        # from 0.998 to as low as -0.21, which looks exactly like a broken model
        # and is entirely an artefact of the readout.
        b_ins = d["B_ins"]                                   # (S, 3, 3)
        m = rotation_matrix(ypr) @ (np.ones(3) / np.sqrt(3.0))
        hep.append(array.project(np.einsum("sck,k->sc", b_ins, m)[:, :, None], ori)[:, 0]
                   * a.source_nam * 1e-9 * 1e15)
        # CFA: distributed myocardium driven by the measured moment
        per = np.einsum("scnk,nk->scn", d["B_myo"].reshape(n_site, 3, -1, 3), myo_ori)
        lc = array.project(per, ori)
        cfa_r.append(lc @ amps[:, rpk] * 1e15)
        cfa_t.append(lc @ amps[:, erp] * 1e15)

    for tag, data, title, unit in (
        ("hep", hep, f"HEP: {a.source_nam:.0f} nA.m insula source", "fT"),
        ("cfa_rpeak", cfa_r, "CFA at the R peak", "fT"),
        ("cfa_hef", cfa_t, "CFA at the HEP latency (650 ms)", "fT"),
    ):
        rad = [v[:n_site] for v in data]              # radial channels
        vlim = float(np.abs(np.array(rad)).max())
        fig, axes = plt.subplots(3, 3, figsize=(10.6, 11.4))
        for ax, v, nm, ypr, hxy in zip(axes.ravel(), rad, names, yprs, heart_xy):
            im = topo(ax, xy, v, vlim, heart_xy=hxy, yaw_deg=float(ypr[0]))
            ax.set_title(f"{nm}\npeak {np.abs(v).max():,.0f} {unit}",
                         fontsize=9.5, loc="center")
        spread = np.array([np.abs(v).max() for v in rad])
        corr = np.array([np.corrcoef(v, rad[0])[0, 1] for v in rad])
        sub = (f"peak {spread.min():,.0f} - {spread.max():,.0f} {unit} "
               f"({spread.max()/max(spread.min(),1e-12):.2f}x);  head-frame "
               f"topography r vs still: {corr.min():.3f} - {corr.max():.3f}")
        fig.suptitle(
            f"{title}\nradial channels, room frame    {sub}\n"
            f"drawn in the ROOM's frame: the head physically turns (grey nose), "
            f"the heart (red) never moves",
            fontsize=12, x=0.02, ha="left")
        cb = fig.colorbar(im, ax=axes, shrink=0.42, pad=0.02, location="right")
        cb.set_label(unit)
        out = a.dir / f"topo_{tag}.png"
        fig.savefig(out, dpi=a.dpi, bbox_inches="tight"); plt.close(fig)
        print("figure:", out, f"| spread {spread.max()/max(spread.min(),1e-12):.3f}x")
    return 0


if __name__ == "__main__":
    sys.exit(main())
